// Builds src/styles/light-generated.css: for every colour the dark-theme codemod changed, restore the
// original light value under html[data-theme=light]. Compares each stylesheet with its version before
// the dark conversion (commit db52ac0^), rule by rule (selector + at-rule context + occurrence).
import postcss from 'postcss';
import { execSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';

const BASE = 'db52ac0~1';
const files = process.argv.slice(2);
const SCOPE = 'html[data-theme="light"]';
const ctxOf = (node) => { const a = []; let p = node.parent; while (p && p.type !== 'root') { if (p.type === 'atrule' && p.name !== 'layer') a.unshift('@' + p.name + ' ' + p.params); p = p.parent } return a };
function keyed(root) {
  const map = new Map(), seen = new Map();
  root.walkRules(r => {
    if (r.parent?.type === 'atrule' && /keyframes/.test(r.parent.name)) return;
    const base = ctxOf(r).join('|') + '§' + r.selector.replace(/\s+/g, ' ').trim();
    const n = (seen.get(base) || 0) + 1; seen.set(base, n);
    map.set(base + '#' + n, r);
  });
  return map;
}
function scopeSelector(sel) {
  return sel.split(',').map(s => {
    s = s.trim();
    if (/^:root\b/.test(s)) return SCOPE + s.slice(5);
    if (/^html\b/.test(s)) return SCOPE + s.slice(4);
    return `${SCOPE} ${s}`;
  }).join(',\n');
}
const out = postcss.root();
let total = 0;
for (const file of files) {
  let original;
  try { original = execSync(`git show ${BASE}:${file}`, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64e6 }) } catch (e) { console.error("skip", file, e.message.slice(0, 80)); continue }
  const before = keyed(postcss.parse(original)), after = keyed(postcss.parse(await readFile(file, 'utf8')));
  for (const [key, rule] of after) {
    const old = before.get(key); if (!old) continue;
    const oldDecls = new Map(); old.each(d => { if (d.type === 'decl') oldDecls.set(d.prop, d) });
    const changes = [];
    rule.each(d => {
      if (d.type !== 'decl') return;
      const o = oldDecls.get(d.prop);
      if (!o) { if (d.prop === 'color' && d.value === '#050806') changes.push({ prop: 'color', value: 'revert-layer', important: d.important }); return }
      if (o.value !== d.value || o.important !== d.important) changes.push({ prop: d.prop, value: o.value, important: o.important || d.important });
    });
    if (!changes.length) continue;
    let parent = out;
    for (const c of ctxOf(rule)) {
      const [name, ...params] = c.slice(1).split(' ');
      let at = parent.nodes.find(n => n.type === 'atrule' && n.name === name && n.params === params.join(' '));
      if (!at) { at = postcss.atRule({ name, params: params.join(' ') }); parent.append(at) }
      parent = at;
    }
    const r = postcss.rule({ selector: scopeSelector(rule.selector) });
    for (const c of changes) r.append(postcss.decl(c));
    parent.append(r); total += changes.length;
  }
}
await writeFile('src/styles/light-generated.css', '/* Generated by scripts/theme/light-gen.mjs: the original light colours, restored when light mode is on. */\n' + out.toString() + '\n');
console.log('light overrides:', total);
