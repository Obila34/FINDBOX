// Keeps the frosted sign-in card dark in light mode: copies every .fa-card rule from cinema.css
// under html[data-theme=light] .fb-dark-scope with !important, outranking the light overrides.
import postcss from 'postcss'; import { readFile, writeFile } from 'node:fs/promises';
const src = postcss.parse(await readFile('src/styles/cinema.css', 'utf8')); const out = postcss.root();
src.walkRules(r => {
  if (!r.selector.includes('.fa-card')) return;
  const sel = r.selector.split(',').map(s => `html[data-theme="light"] .fb-dark-scope ${s.trim()}`).join(',\n');
  const n = postcss.rule({ selector: sel });
  r.walkDecls(d => n.append(postcss.decl({ prop: d.prop, value: d.value, important: true })));
  out.append(n);
});
await writeFile('src/styles/light-dark-scope.css', '/* Generated by scripts/theme/scope-gen.mjs: the sign-in card stays dark over its photo in light mode. */\n' + out.toString() + '\n');
console.log(out.nodes.length, 'rules');
